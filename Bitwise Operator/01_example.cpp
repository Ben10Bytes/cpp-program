#include<iostream>
using namespace std;
int main(){
    
    int a = 4;
    int b = 6;


    // & = AND OPERATOR
    // | = OR operator
    // ~ = NOT OPERATOR  
    // ^ = XOR OPERATOR 

    cout<<" a & b : " << (a & b) << endl;
    cout<<" a | b : " << (a | b) << endl;
    cout<<" ~b : " << ( ~b ) << endl;
    cout<<" a ^ b : " << (a ^ b) << endl;

    
    
}